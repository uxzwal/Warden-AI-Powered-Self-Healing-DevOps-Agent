"""Pydantic schemas and domain models for Warden AI DevOps Agent.

Enforces strict validation on AI outputs, remediation parameters,
service configurations, metrics, and verification results.
"""

from enum import Enum
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class RemediationAction(str, Enum):
    """Allowlist of permitted remediation actions.
    
    The agent and remediation engine are strictly prohibited from
    executing any action outside this enumeration.
    """
    INCREASE_POOL_LIMIT = "increase_pool_limit"
    RESET_SERVICE_CONFIG = "reset_service_config"
    NO_OP = "no_op"


class IncidentPayload(BaseModel):
    """Payload for deliberately injecting an incident into the payment service."""
    severity: Literal["LOW", "MEDIUM", "HIGH", "CRITICAL"] = "HIGH"
    max_connections: int = Field(default=2, ge=1, le=10)
    processing_delay_ms: float = Field(default=250.0, ge=10.0, le=5000.0)
    reason: str = Field(default="Connection pool starvation triggered by synthetic DB lock")


class ServiceConfig(BaseModel):
    """Runtime configuration for the Payment Gateway Simulator."""
    service_name: str = "Payment Gateway Simulator"
    max_connections: int = Field(default=50, ge=1, le=500)
    baseline_max_connections: int = Field(default=50, ge=1, le=500)
    processing_delay_ms: float = Field(default=100.0, ge=0.0, le=5000.0)
    baseline_processing_delay_ms: float = Field(default=100.0, ge=0.0, le=5000.0)
    is_degraded: bool = False
    incident_description: Optional[str] = None
    admin_token: str = "warden-admin-secret-token"
    port: int = 8001


class ServiceMetrics(BaseModel):
    """Live telemetry and operational metrics from the payment service."""
    total_requests: int = 0
    successful_requests: int = 0
    rate_limited_503: int = 0
    other_errors: int = 0
    active_connections: int = 0
    max_connections: int = 50
    processing_delay_ms: float = 100.0
    failure_rate: float = 0.0
    uptime_seconds: float = 0.0
    is_degraded: bool = False
    recent_logs: List[Dict[str, Any]] = Field(default_factory=list)


class ActionParameters(BaseModel):
    """Validated parameters for safe remediation actions.
    
    Enforces explicit safety bounds on any configuration mutations:
    - max_connections: must be within [5, 200]
    - processing_delay_ms: must be within [10.0, 5000.0]
    """
    max_connections: Optional[int] = None
    processing_delay_ms: Optional[float] = None
    reason: Optional[str] = None

    @field_validator("max_connections")
    @classmethod
    def validate_max_connections(cls, v: Optional[int]) -> Optional[int]:
        if v is not None:
            if v < 5 or v > 200:
                raise ValueError(f"max_connections {v} is outside safe limits [5, 200]")
        return v

    @field_validator("processing_delay_ms")
    @classmethod
    def validate_processing_delay(cls, v: Optional[float]) -> Optional[float]:
        if v is not None:
            if v < 10.0 or v > 5000.0:
                raise ValueError(f"processing_delay_ms {v} is outside safe limits [10.0, 5000.0]")
        return v


class AgentDiagnosis(BaseModel):
    """Structured Pydantic response generated by Warden AI Agent (Demo or Live).
    
    Contains diagnostic evidence, root cause hypothesis, safe remediation proposal,
    and verification plan.
    """
    incident_summary: str
    severity: Literal["LOW", "MEDIUM", "HIGH", "CRITICAL"]
    confidence: float = Field(ge=0.0, le=1.0)
    evidence: List[str]
    root_cause_hypothesis: str
    action: Literal["increase_pool_limit", "reset_service_config", "no_op"]
    parameters: Dict[str, Any] = Field(default_factory=dict)
    expected_outcome: str
    verification_plan: str
    explanation: str
    mode: Literal["demo", "live"] = "demo"
    reasoning_model: Optional[str] = None
    tavily_research: Optional[List[Dict[str, Any]]] = None

    @model_validator(mode="after")
    def validate_action_and_params(self) -> "AgentDiagnosis":
        # Validate that the action is one of the strictly allowed actions
        if self.action not in [a.value for a in RemediationAction]:
            raise ValueError(f"Action '{self.action}' is not in the allowed remediation actions list.")
        
        # If action is increase_pool_limit, parameters must validate against ActionParameters
        if self.action == RemediationAction.INCREASE_POOL_LIMIT.value:
            ActionParameters(**self.parameters)
        return self


class VerificationResult(BaseModel):
    """Result of automated concurrency verification executed against the running service."""
    total_requests: int
    success_200: int
    rate_limited_503: int
    other_errors: int
    timeouts: int
    failure_rate: float
    avg_latency_ms: float
    p95_latency_ms: float
    p99_latency_ms: float
    status: Literal["HEALTHY", "DEGRADED", "FAILED"]
    timestamp: str
    details: str = ""


class AuditEvent(BaseModel):
    """Structured audit trail record for compliance and post-mortem analysis."""
    id: str
    timestamp: str
    event_type: str
    actor: str  # e.g., "AI_AGENT", "OPERATOR", "VERIFIER", "SYSTEM"
    summary: str
    details: Dict[str, Any] = Field(default_factory=dict)
    status: str = "INFO"
